using System.Data;
using System.Diagnostics;
using Microsoft.Data.SqlClient;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using RequestsManagement.Core.Enums;

namespace RequestsManagement.Infrastructure.DAL;

/// <summary>
/// Generates test data. Re-runnable: it clears both tables first. Deterministic: a fixed Random seed
/// produces the same titles/organizations/statuses on every run, so measurements are comparable.
/// SqlBulkCopy is used because inserting 100K rows through EF change tracking would take minutes.
/// </summary>
public sealed class DataSeeder(AppDbContext db, TimeProvider clock, ILogger<DataSeeder> logger)
{
    public const int DefaultCount = 100_000;
    private const int RandomSeed = 20261019;

    private static readonly string[] OrgPrefixes =
        ["Alpha", "Beta", "Gamma", "Delta", "Omega", "Nova", "Prime", "Global", "United", "Bright",
         "Blue", "Green", "Silver", "Golden", "North", "South", "Metro", "Smart", "Tech", "Urban"];
    private static readonly string[] OrgSuffixes =
        ["Industries", "Solutions", "Logistics", "Systems", "Foods", "Health", "Finance", "Labs", "Retail", "Energy",
         "Media", "Consulting", "Holdings", "Group", "Services"];
    private static readonly string[] Subjects =
        ["Payment", "Invoice", "Account", "Contract", "Delivery", "Report", "Access", "Employee", "Permit", "Refund"];
    private static readonly string[] Issues =
        ["delayed", "missing", "update request", "approval needed", "error", "question", "cancellation", "renewal",
         "correction", "complaint"];

    public async Task<bool> IsEmptyAsync(CancellationToken ct) => !await db.Requests.AnyAsync(ct);

    public async Task SeedAsync(int count, CancellationToken ct)
    {
        var sw = Stopwatch.StartNew();

        // History references Requests (FK), so it is cleared first. TRUNCATE is not allowed on a table referenced
        // by a FK, so Requests uses DELETE.
        await db.Database.ExecuteSqlRawAsync("TRUNCATE TABLE RequestStatusHistory; DELETE FROM Requests;", ct);

        var table = BuildTable(count);

        var connection = (SqlConnection)db.Database.GetDbConnection();
        await db.Database.OpenConnectionAsync(ct);
        try
        {
            // Ids are written explicitly (1..count) instead of relying on DBCC CHECKIDENT, whose next value differs
            // between a never-used table (starts at the reseed value, i.e. 0) and a table that had rows (reseed + 1).
            using var bulk = new SqlBulkCopy(connection, SqlBulkCopyOptions.TableLock | SqlBulkCopyOptions.KeepIdentity, null)
            {
                DestinationTableName = "Requests",
                BatchSize = 10_000,
                BulkCopyTimeout = 300
            };
            foreach (DataColumn column in table.Columns)
                bulk.ColumnMappings.Add(column.ColumnName, column.ColumnName); // RowVersion is generated by SQL Server

            await bulk.WriteToServerAsync(table, ct);
        }
        finally
        {
            await db.Database.CloseConnectionAsync();
        }

        // Rows created later through the system continue from count + 1.
        await db.Database.ExecuteSqlAsync($"DBCC CHECKIDENT ('Requests', RESEED, {count})", ct);

        logger.LogInformation("Seeded {Count} requests in {Elapsed} ms", count, sw.ElapsedMilliseconds);
    }

    private DataTable BuildTable(int count)
    {
        var random = new Random(RandomSeed);
        var now = clock.GetUtcNow().UtcDateTime;
        var organizations = OrgPrefixes.SelectMany(p => OrgSuffixes.Select(s => $"{p} {s}")).ToArray(); // 300 orgs
        var assignees = Enumerable.Range(1, 50).Select(i => $"agent{i:D2}").ToArray();

        var table = new DataTable();
        table.Columns.Add("Id", typeof(int));
        table.Columns.Add("Title", typeof(string));
        table.Columns.Add("OrganizationName", typeof(string));
        table.Columns.Add("Status", typeof(byte));
        table.Columns.Add("Priority", typeof(byte));
        table.Columns.Add("AssignedTo", typeof(string));
        table.Columns.Add("CreatedAt", typeof(DateTime));
        table.Columns.Add("UpdatedAt", typeof(DateTime));

        for (var i = 0; i < count; i++)
        {
            var status = PickWeighted(random, (RequestStatus.New, 25), (RequestStatus.InProgress, 30),
                (RequestStatus.Waiting, 15), (RequestStatus.Completed, 30));
            var priority = PickWeighted(random, (Priority.Low, 40), (Priority.Medium, 40), (Priority.High, 20));
            var createdAt = now.AddMinutes(-random.Next(0, 2 * 365 * 24 * 60)); // last 2 years
            var updatedAt = status == RequestStatus.New ? createdAt : createdAt.AddMinutes(random.Next(1, 30 * 24 * 60));
            if (updatedAt > now) updatedAt = now;

            // ~40% of New requests (about 10% of all requests) are not yet assigned
            var assignedTo = status == RequestStatus.New && random.Next(10) < 4 ? null : assignees[random.Next(assignees.Length)];

            table.Rows.Add(
                i + 1,
                $"{Subjects[random.Next(Subjects.Length)]} {Issues[random.Next(Issues.Length)]} #{i + 1}",
                organizations[random.Next(organizations.Length)],
                (byte)status,
                (byte)priority,
                (object?)assignedTo ?? DBNull.Value,
                createdAt,
                updatedAt);
        }

        return table;
    }

    private static T PickWeighted<T>(Random random, params (T Value, int Weight)[] options)
    {
        var roll = random.Next(options.Sum(o => o.Weight));
        foreach (var (value, weight) in options)
        {
            if (roll < weight) return value;
            roll -= weight;
        }
        return options[^1].Value;
    }
}
